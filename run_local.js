// Runs the two Code nodes from the workflow JSON against the sample data. No n8n, no API calls.
// Usage: node tests/run_local.js [--write-samples]
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const wf = JSON.parse(fs.readFileSync(path.join(root, 'workflow/weekly-ops-status.json'), 'utf8'));

// Fixed "today" so the sample output is reproducible
const FAKE = new Date('2026-10-05T09:00:00');
const RealDate = Date;
global.Date = class extends RealDate {
  constructor(...a) { if (a.length === 0) super(FAKE.getTime()); else super(...a); }
  static now() { return FAKE.getTime(); }
};

function parseCsv(text) {
  const rows = []; let row = [], cur = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) { if (ch === '"' && text[i + 1] === '"') { cur += '"'; i++; } else if (ch === '"') q = false; else cur += ch; }
    else if (ch === '"') q = true;
    else if (ch === ',') { row.push(cur); cur = ''; }
    else if (ch === '\n') { row.push(cur); rows.push(row); row = []; cur = ''; }
    else if (ch !== '\r') cur += ch;
  }
  if (cur || row.length) { row.push(cur); rows.push(row); }
  const [head, ...body] = rows;
  return body.map(r => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])));
}
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const node = n => wf.nodes.find(x => x.name === n);
const code = n => node(n).parameters.jsCode;

const config = Object.fromEntries(node('Config').parameters.assignments.assignments.map(a => [a.name, a.value]));
const sources = {
  'Config': [config],
  'Read Workstreams': parseCsv(read('samples/input/workstreams.csv')),
  'Read Risks and Decisions': parseCsv(read('samples/input/risks_decisions.csv')),
  'Read Calendar': JSON.parse(read('samples/input/calendar_events.json')),
};
const $ = name => {
  if (!(name in sources)) throw new Error('No such node: ' + name);
  const items = sources[name].map(json => ({ json }));
  return { all: () => items, first: () => items[0] };
};
const run = (name, input) => new Function('$', '$input', code(name))($, { first: () => ({ json: input }) });

const consolidated = run('Consolidate', {})[0].json;
sources['Consolidate'] = [consolidated];

const assert = (cond, msg) => { if (!cond) { console.error('FAIL:', msg); process.exitCode = 1; } else console.log('ok  ', msg); };
const c = consolidated.facts.counts;
assert(c.workstreams === 6, '6 workstreams read');
assert(c.green === 3 && c.amber === 2 && c.red === 1, 'RAG counts 3/2/1');
assert(c.overdueMilestones === 1, 'one overdue milestone (Site readiness)');
assert(c.staleUpdates === 1, 'one stale update (Compliance filings)');
assert(c.openDecisions === 2 && c.decisionsDueThisWeek === 1, 'closed decision excluded; 1 due within 7 days');
assert(c.openRisks === 3 && c.highRisks === 1, '3 open risks, 1 high');
assert(consolidated.facts.events.length === 3, 'calendar filtered to 3 checkpoints (lunch and supplier call dropped)');
assert(consolidated.aiRequest.messages[0].content.includes('Weekly data'), 'AI request built');

// With AI
const aiResp = JSON.parse(read('tests/mock-ai-response.json'));
const withAi = run('Build Report', aiResp)[0].json;
assert(withAi.aiUsed === true, 'AI summary parsed');
assert(withAi.subject.includes('1 red') && withAi.subject.includes('1 decision due'), 'subject carries red count and decisions due');

// Without AI (node disabled or failed): input is the Consolidate output / an error object
const fallback = run('Build Report', { error: 'API unavailable' })[0].json;
assert(fallback.aiUsed === false && fallback.markdown.includes('Summary generated by rules'), 'rule-based fallback works');
const passthrough = run('Build Report', consolidated)[0].json;
assert(passthrough.aiUsed === false, 'disabled AI node (pass-through) works');

if (process.argv.includes('--write-samples')) {
  fs.writeFileSync(path.join(root, 'samples/output/weekly_status.md'), withAi.markdown + '\n');
  fs.writeFileSync(path.join(root, 'samples/output/weekly_status.html'), '<!doctype html><meta charset="utf-8"><title>' + withAi.subject + '</title>' + withAi.html + '\n');
  fs.writeFileSync(path.join(root, 'samples/output/weekly_status_no_ai.md'), fallback.markdown + '\n');
  fs.writeFileSync(path.join(root, 'samples/output/slack_message.txt'), withAi.slackText + '\n');
  console.log('Samples written.');
}
